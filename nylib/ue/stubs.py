def _comment_column(lines_and_comments: list[tuple[str, str]]) -> list[str]:
    width = min(100, max((len(line) for line, c in lines_and_comments if c), default=0) + 2)
    out = []
    for line, comment in lines_and_comments:
        if not comment:
            out.append(line)
            continue
        pad = ' ' * max(2, width - len(line))
        out.append(f'{line}{pad}# {comment}')
    return out


def _output_unreadable(t, records_by_path: dict, depth: int = 0) -> bool:
    if depth > 32:
        return False
    if t.kind in ('OptionalProperty', UNKNOWN_KIND):
        return True
    if t.kind == 'StructProperty':
        if not t.struct or not isinstance(records_by_path.get(t.struct), StructRecord):
            return True
        members = _flat_members(t.struct, records_by_path)
        if members is None:
            return True
        return any(_output_unreadable(m.type, records_by_path, depth + 1) for m in members)
    for sub in (t.inner, t.element, t.key, t.value):
        if sub is not None and _output_unreadable(sub, records_by_path, depth + 1):
            return True
    return False


def _signature_line(attr: str, frec: FunctionRecord, ctx, records_by_path: dict) -> str:
    """The `def {attr}(...) -> ...: ...` line of a declared function (the signature rule)."""
    try:
        lay = calls.layout(frec)
    except ValueError:
        return f'    def {attr}(self, *args: _Any_, **kwargs: _Any_) -> _Any_: ...  # refused in v1: a parameter lies past params_size'
    receiver = 'self'
    if any(py_name(p.name) == 'self' for p in lay.inputs):
        receiver = '_self'
        while any(py_name(p.name) == receiver for p in lay.inputs):
            receiver = '_' + receiver
    used = {receiver}
    items = []  # (name, param, refused, renamed)
    first_refused = None
    for i, p in enumerate(lay.inputs):
        cand = py_name(p.name)
        if cand != receiver and cand not in used and usable(cand):
            name, renamed = cand, False
        else:
            name = f'_p{i}'
            while name in used:
                name += '_'
            renamed = True
        used.add(name)
        refused = _is_refused_arg(p, ctx, records_by_path)
        if refused and first_refused is None:
            first_refused = i
        items.append((name, p, refused, renamed))
    relevant_renames = [i for i, (_, _, _, renamed) in enumerate(items) if renamed and (first_refused is None or i < first_refused)]
    slash_after = max(relevant_renames) if relevant_renames else None
    tokens = [receiver]
    star_done = False
    for i, (name, p, refused, _) in enumerate(items):
        if first_refused is not None and i == first_refused + 1 and not star_done:
            tokens.append('*')
            star_done = True
        tokens.append(f'{name}: _Never_ = ...' if refused else f'{name}: {_arg_expr(p, ctx, records_by_path, ref=(calls.param_role(p) == "ref"))}')
        if slash_after == i:
            tokens.append('/')
    if not lay.outputs:
        ret = ctx.builtin('None')
    elif len(lay.outputs) == 1:
        ret = _out_expr(lay.outputs[0], ctx, records_by_path)
    else:
        ret = _own_name(ctx, _result_key(frec.path))
    comments = []
    if frec.flags & EFunctionFlags.Static:
        comments.append('static')
    if any(p.type.kind == 'StructProperty' and p.type.struct == '/Script/Engine.LatentActionInfo' and calls.param_role(p) != 'local'
           for p in frec.params):
        comments.append('refused in v1: latent function')
    for p in lay.outputs:
        if _output_unreadable(p.type, records_by_path):
            comments.append(f'refused in v1: output {p.name!r} cannot be read')
            break
    line = f'    def {attr}({", ".join(tokens)}) -> {ret}: ...'
    if comments:
        line += '  # ' + '; '.join(comments)
    return line


def _class_header(rec, ctx) -> str:
    if isinstance(rec, EnumRecord):
        name = _own_name(ctx, _enum_key(rec.path))
        return f'class {name}(_IntEnum_):'
    is_class = isinstance(rec, ClassRecord)
    key = _class_key(rec.path) if is_class else _struct_key(rec.path)
    name = _own_name(ctx, key)
    base = None
    if rec.super is not None:
        base = ctx.name(_class_key(rec.super) if is_class else _struct_key(rec.super))
    if base is None:
        base = '_UObjectProxy_' if is_class else '_StructView_'
    return f'class {name}({base}):'


def _member_comment(p: PropertyRecord, get_expr: str) -> str:
    t = p.type
    if t.kind == 'BoolProperty' and t.field_mask is not None and t.field_mask != 0xFF and t.byte_offset is not None:
        base = f'0x{p.offset + t.byte_offset:X} bit {t.field_mask.bit_length() - 1}'
    else:
        base = f'0x{p.offset:X}'
    suffix = f' [{p.array_dim}]' if p.array_dim > 1 else ''
    if get_expr == '_Any_':
        if t.kind == 'StructProperty' and t.struct:
            return f'{base}{suffix}, {t.struct} not in these stubs'
        return f'{base}{suffix}, not readable in v1 ({t.prop})'
    return base + suffix


def _own_predefined_name(rec, predefined) -> str | None:
    hit = _declared_predefined(rec, predefined)
    return hit[0] if hit is not None else None


def _type_block(rec, ctx, records_by_path: dict, predefined) -> list[str]:
    header = _class_header(rec, ctx)
    if isinstance(rec, EnumRecord):
        return [header] + _enum_body(rec)
    is_class = isinstance(rec, ClassRecord)
    if not is_class:
        members = _flat_members(rec.path, records_by_path)
        if members == []:
            header = header + '  # no reflected members: passed as zero bytes'
    member_lines: list[tuple[str, str]] = []
    taken: set[str] = set()
    for p in rec.properties:
        names = member_names(p.name)
        n = next((x for x in names if usable(x) and x not in taken), None)
        if n is not None:
            get = _get_expr(p, ctx, records_by_path)
            member_lines.append((f'    {n}: {get}', _member_comment(p, get)))
        taken.update(names)
    pre = _declared_predefined(rec, predefined)
    if pre is not None:
        pname, pvalue, pkey = pre
        expr = _predefined_type_expr(rec.path, ctx)
        member_lines.append((f'    {pname}: {expr}', f'0x{pvalue:X}, not reflected ({pkey})'))
        taken.add(pname)
    aligned = _comment_column(member_lines)
    func_lines = []
    if is_class:
        for frec in rec.functions.values():
            names = member_names(frec.name)
            if frec.flags & EFunctionFlags.Delegate:
                taken.update(names)
                continue
            attr = next((x for x in names if usable(x) and x not in taken), None)
            if attr is not None:
                func_lines.append(_signature_line(attr, frec, ctx, records_by_path))
            taken.update(names)
    body = aligned + func_lines
    if not body:
        body = ['    ...']
    return [header] + body


def _enum_body(rec: EnumRecord) -> list[str]:
    seen: set[str] = set()
    lines = []
    for raw, value in rec.values:
        m = _enum_member_name(raw)
        if m in seen:
            continue
        seen.add(m)
        if usable(m):
            lines.append(f'    {m} = {value}')
    return lines or ['    ...']


def _value_fields(rec: StructRecord, records_by_path: dict):
    members = _flat_members(rec.path, records_by_path)
    if members is None:
        return None, None
    fields = collections.namedtuple('_V', [py_name(m.name) for m in members], rename=True)._fields if members else ()
    return fields, members


def _value_class_lines(rec: StructRecord, ctx, records_by_path: dict) -> list[str]:
    name = _own_name(ctx, _value_key(rec.path))
    fields, members = _value_fields(rec, records_by_path)
    lines = [f'class {name}(_StructValue_):']
    if fields is None:
        lines.append('    ...')
        return lines
    usable_pairs = [(f, m) for f, m in zip(fields, members) if usable(f)]
    if not usable_pairs:
        lines.append('    ...')
        return lines
    for f, m in usable_pairs:
        lines.append(f'    {f}: {_out_expr(m, ctx, records_by_path)}')
    params = ', '.join(f'{f}: {_out_expr(m, ctx, records_by_path)} = ...' for f, m in usable_pairs)
    lines.append(f'    def _replace(self, *, {params}) -> {name}: ...')
    return lines


def _result_fields(frec: FunctionRecord, rec, records_by_path: dict):
    outputs = calls.layout(frec).outputs
    owner = _owner_path(frec)
    owner_cpp = _owner_cpp_name(owner, rec, records_by_path)
    field_names = [py_name(p.name) for p in outputs]
    try:
        fields = collections.namedtuple(f'{owner_cpp}_{py_name(frec.name)}', field_names, rename=True)._fields
    except ValueError:
        fields = collections.namedtuple('CallResult', field_names, rename=True)._fields
    return fields, outputs


def _result_class_lines(frec: FunctionRecord, rec, ctx, records_by_path: dict) -> list[str]:
    name = _own_name(ctx, _result_key(frec.path))
    fields, outputs = _result_fields(frec, rec, records_by_path)
    simple = all(usable(f) and not f.startswith('_') for f in fields)
    lines = []
    if simple:
        lines.append(f'class {name}(_NamedTuple_):')
        for f, p in zip(fields, outputs):
            lines.append(f'    {f}: {_out_expr(p, ctx, records_by_path)}')
    else:
        types = ', '.join(_out_expr(p, ctx, records_by_path) for p in outputs)
        lines.append(f'class {name}({ctx.builtin("tuple")}[{types}]):')
        any_usable = False
        for f, p in zip(fields, outputs):
            if usable(f):
                any_usable = True
                lines.append('    @property')
                lines.append(f'    def {f}(self) -> {_out_expr(p, ctx, records_by_path)}: ...')
        if not any_usable:
            lines.append('    ...')
    return lines


# --------------------------------------------------------------------------- module assembly


def _module_declared_functions(rec: ClassRecord):
    for frec in rec.functions.values():
        if frec.flags & EFunctionFlags.Delegate:
            continue
        try:
            n = len(calls.layout(frec).outputs)
        except ValueError:
            n = 0
        if n >= 2:
            yield frec


def _collect_module_refs(mod, records_by_path: dict, predefined, written: dict) -> set[str]:
    ctx = _CollectCtx(written)
    for rec in mod.types:
        _class_header(rec, ctx)
        if isinstance(rec, EnumRecord):
            continue
        for p in rec.properties:
            _get_expr(p, ctx, records_by_path)
        pre = _declared_predefined(rec, predefined)
        if pre is not None:
            _predefined_type_expr(rec.path, ctx)
        if isinstance(rec, ClassRecord):
            for frec in rec.functions.values():
                if frec.flags & EFunctionFlags.Delegate:
                    continue
                try:
                    lay = calls.layout(frec)
                except ValueError:
                    continue
                for p in lay.inputs:
                    _arg_expr(p, ctx, records_by_path, ref=(calls.param_role(p) == 'ref'))
                for p in lay.outputs:
                    _out_expr(p, ctx, records_by_path)
        else:
            _, members = _value_fields(rec, records_by_path)
            if members:
                for m in members:
                    _out_expr(m, ctx, records_by_path)
    return ctx.refs


def _assign_imports(mod, names: _Names, refs: set, written: dict, by_chain: dict, names_of: dict) -> None:
    used = {n.casefold() for n in names.local.values()}

    def claim(base: str) -> str:
        name, n = base, 2
        while name.casefold() in used:
            name = f'{base}_{n}'
            n += 1
        used.add(name.casefold())
        return name

    for n in SUPPORT_NAMES:
        names.support_alias[n] = claim(n)
    groups: dict[tuple, list[str]] = {}
    for key in refs:
        home = written[key]
        if home == mod.modpath:
            continue
        groups.setdefault(home, []).append(key)
    for home in sorted(groups, key=lambda h: by_chain[h].file):
        keys = sorted(groups[home], key=lambda k: names_of[home].local[k])
        for key in keys:
            names.cross[key] = claim(names_of[home].local[key])


def _render_module(mod, header_text: str, written: dict, names_of: dict, by_chain: dict, records_by_path: dict, predefined) -> str:
    names = names_of[mod.modpath]
    ctx = _RenderCtx(names, written)
    header_lines = [header_text, *_FIXED_IMPORTS]
    support_pairs = [(n, names.support_alias[n]) for n in SUPPORT_NAMES]
    support_txt = ', '.join(f'{n} as {a}' if a != n else n for n, a in support_pairs)
    import_lines = [f'from {_rel_import(mod.folder, ())} import {support_txt}']
    groups: dict[tuple, list[tuple[str, str]]] = {}
    for key, alias in names.cross.items():
        home = written[key]
        groups.setdefault(home, []).append((names_of[home].local[key], alias))
    for home in sorted(groups, key=lambda h: by_chain[h].file):
        pairs = sorted(groups[home], key=lambda pr: pr[0])
        names_txt = ', '.join(f'{n} as {a}' if a != n else n for n, a in pairs)
        import_lines.append(f'from {_rel_import(mod.folder, home)} import {names_txt}')
    parts = ['\n'.join(header_lines), '\n'.join(import_lines)]
    blocks: list[list[str]] = []
    order = _emission_order(mod.types)
    for rec in order:
        if isinstance(rec, ClassRecord):
            for frec in _module_declared_functions(rec):
                fields, outputs = _result_fields(frec, rec, records_by_path)
                ctx.own_taken = set(fields)
                blocks.append(_result_class_lines(frec, rec, ctx, records_by_path))
            ctx.own_taken = _own_taken(rec, _own_predefined_name(rec, predefined))
            blocks.append(_type_block(rec, ctx, records_by_path, predefined))
        elif isinstance(rec, StructRecord):
            ctx.own_taken = _own_taken(rec, _own_predefined_name(rec, predefined))
            blocks.append(_type_block(rec, ctx, records_by_path, predefined))
            fields, _members = _value_fields(rec, records_by_path)
            ctx.own_taken = set(fields) if fields else set()
            blocks.append(_value_class_lines(rec, ctx, records_by_path))
        else:
            ctx.own_taken = set()
            blocks.append(_type_block(rec, ctx, records_by_path, predefined))
    if names.aliases_needed:
        parts.append('\n'.join(f'_{n}_ = {n}' for n in sorted(names.aliases_needed)))
    body_text = '\n\n\n'.join('\n'.join(b) for b in blocks)
    return '\n\n'.join(parts) + '\n\n\n' + body_text + '\n'


def _header_line(package: str, source_text: str) -> str:
    text = f'# {package} - generated by nylib.ue from {source_text}, do not edit'
    return ''.join(c if ord(c) >= 0x20 and c != '\x7f' else '?' for c in text)


def _support_header_line(source_text: str) -> str:
    text = f'# stub support types - generated by nylib.ue from {source_text}, do not edit'
    return ''.join(c if ord(c) >= 0x20 and c != '\x7f' else '?' for c in text)


