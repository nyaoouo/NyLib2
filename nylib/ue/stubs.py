def _scandir_names(folder: str) -> dict:
    try:
        return {e.name: e for e in os.scandir(folder)}
    except OSError:
        return {}


def _is_own_file(path: str) -> bool:
    try:
        with open(path, 'r', encoding='utf-8', errors='replace') as f:
            line1 = f.readline().rstrip('\r\n')
    except OSError:
        return False
    return bool(HEADER_RE.fullmatch(line1))


def _is_stub_root(path: str) -> bool:
    init = os.path.join(path, '__init__.pyi')
    if _is_link(init):
        return False
    try:
        with open(init, 'r', encoding='utf-8', errors='replace') as f:
            line1 = f.readline().rstrip('\r\n')
    except OSError:
        return False
    return bool(_SUPPORT_HEADER_RE.fullmatch(line1))


def _folder_is_own(path: str) -> bool:
    for dirpath, dirnames, filenames in os.walk(path):
        dirnames[:] = [d for d in dirnames if not _is_link(os.path.join(dirpath, d))]
        for fn in filenames:
            fp = os.path.join(dirpath, fn)
            if _is_link(fp):
                continue
            if not fn.endswith('.pyi') or not _is_own_file(fp):
                return False
    return True


def _check_case(path: str, is_dir: bool, renames: list) -> None:
    parent, base = os.path.dirname(path), os.path.basename(path)
    siblings = _scandir_names(parent)
    if base in siblings:
        return
    cf = base.casefold()
    for name, entry in siblings.items():
        if name.casefold() != cf:
            continue
        full = os.path.join(parent, name)
        if is_dir:
            if entry.is_dir(follow_symlinks=False) and not _is_link(full) and _folder_is_own(full):
                renames.append((full, path))
                return
        elif entry.is_file(follow_symlinks=False) and not _is_link(full) and _is_own_file(full):
            renames.append((full, path))
            return
        raise FileExistsError(f'{path} differs from {full} only in case and was not written by nylib.ue; rename or move it '
                               f'(nothing was written)')


def _write_module_files(out: str, planned: dict) -> tuple[int, int]:
    """planned: path -> text. Runs the folder check, writes, then cleans stale files; returns (files, removed)."""
    norm = lambda p: os.path.normcase(os.path.abspath(p))
    planned_dirs: set[str] = set()
    for p in planned:
        d = os.path.dirname(p)
        while True:
            planned_dirs.add(d)
            if norm(d) == norm(out):
                break
            d = os.path.dirname(d)
    for d in sorted(planned_dirs, key=len):
        if os.path.lexists(d) and (_is_link(d) or not os.path.isdir(d)):
            raise NotADirectoryError(f'{d} exists and is not a folder (nothing was written)')
    renames: list = []
    for d in sorted(planned_dirs, key=len):
        if norm(d) != norm(out):
            _check_case(d, True, renames)
    for p in sorted(planned):
        _check_case(p, False, renames)
    for p in planned:
        entry = _scandir_names(os.path.dirname(p)).get(os.path.basename(p))
        if entry is not None:
            if not entry.is_file(follow_symlinks=False) or _is_link(p) or not _is_own_file(p):
                raise FileExistsError(f'{p} exists and was not written by nylib.ue; move it or choose another out_dir '
                                       f'(nothing was written)')
    init_py = os.path.join(out, '__init__.py')
    if os.path.exists(init_py):
        raise FileExistsError(f'{init_py} would be hidden by the generated stubs; move it or choose another out_dir '
                               f'(nothing was written)')
    for p in planned:
        if p.endswith('.pyi'):
            xpy = p[:-1]
            if os.path.exists(xpy):
                raise FileExistsError(f'{xpy} would be hidden by the generated {p}; move it or choose another out_dir '
                                       f'(nothing was written)')
    for src, dst in sorted(renames, key=lambda r: -len(r[0])):
        os.rename(src, dst)
    leaf_dirs = {os.path.dirname(p) for p in planned}
    for d in sorted(leaf_dirs, key=len):
        os.makedirs(d, exist_ok=True)
    written_norm = set()
    for p, text in planned.items():
        with open(p, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        written_norm.add(norm(p))
    removed = _clean(out, written_norm)
    return len(planned), removed


def _clean(out: str, written_norm: set) -> int:
    removed = 0
    failures: list[str] = []
    out_norm = os.path.normcase(os.path.abspath(out))
    emptied: set[str] = set()
    for dirpath, dirnames, filenames in os.walk(out):
        dirnames[:] = [d for d in dirnames if not _is_link(os.path.join(dirpath, d))
                       and not _is_stub_root(os.path.join(dirpath, d))]  # top-down: links and other stub roots are never entered
        for fn in filenames:
            fp = os.path.join(dirpath, fn)
            if _is_link(fp) or not fn.endswith('.pyi'):
                continue
            if os.path.normcase(os.path.abspath(fp)) in written_norm:
                continue
            if not _is_own_file(fp):
                continue
            try:
                os.remove(fp)
                removed += 1
                emptied.add(os.path.abspath(dirpath))
            except OSError:
                failures.append(fp)
    gone: set[str] = set()
    for folder in sorted(emptied, key=len, reverse=True):
        while os.path.normcase(folder) != out_norm and folder not in gone:
            try:
                if os.listdir(folder):
                    break
                os.rmdir(folder)
            except OSError:
                failures.append(folder)
                break
            gone.add(folder)
            folder = os.path.dirname(folder)
    if failures:
        _log.warning('%d stale files or folders could not be removed (first: %s)', len(failures), failures[0])
    return removed


