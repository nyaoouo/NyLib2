def _tuple_expr(path: str, ctx, records_by_path: dict) -> str:
    members = _flat_members(path, records_by_path)
    if members is None:
        return f'{ctx.builtin("tuple")}[_Any_, ...]'
    if not members:
        return f'{ctx.builtin("tuple")}[()]'
    if len(members) <= 4 and all(m.array_dim == 1 and m.type.kind in _SIMPLE_TUPLE_KINDS for m in members):
        parts = [_type_expr('arg', m.type, ctx) for m in members]
        return f'{ctx.builtin("tuple")}[{", ".join(parts)}]'
    return f'{ctx.builtin("tuple")}[_Any_, ...]'


def _type_expr(mode: str, t, ctx, records_by_path: dict | None = None) -> str:
    """get/arg/out of one PropType; mode is one of 'get', 'arg', 'out'."""
    kind = t.kind
    if kind in _INT_KINDS:
        return ctx.builtin('int')
    if kind in ('FloatProperty', 'DoubleProperty'):
        return ctx.builtin('float')
    if kind == 'BoolProperty':
        return ctx.builtin('bool')
    if kind in ('ByteProperty', 'EnumProperty'):
        e = ctx.name(_enum_key(t.enum)) if t.enum else None
        return f'{e} | {ctx.builtin("int")}' if e else ctx.builtin('int')
    if kind == 'NameProperty':
        return ctx.builtin('str') if mode == 'arg' else ctx.support('FName')
    if kind in ('StrProperty', 'AnsiStrProperty', 'Utf8StrProperty'):
        return ctx.builtin('str')
    if kind == 'TextProperty':
        return '_FTextCopy_' if mode == 'out' else '_FTextValue_'
    if kind == 'ObjectProperty':
        c = _class_ref(ctx, t.cls)
        return f'{c} | {ctx.builtin("int")} | {ctx.builtin("None")}' if mode == 'arg' else f'{c} | {ctx.builtin("None")}'
    if kind == 'ClassProperty':
        c = _uclass_ref(ctx)
        return f'{c} | {ctx.builtin("int")} | {ctx.builtin("None")}' if mode == 'arg' else f'{c} | {ctx.builtin("None")}'
    if kind == 'InterfaceProperty':
        if mode == 'arg':
            return ctx.builtin('None')
        return f'{_uobj_ref(ctx)} | {ctx.builtin("None")}'
    if kind == 'WeakObjectProperty':
        c = _class_ref(ctx, t.cls)
        tw = ctx.support('TWeakObjectPtr')
        if mode == 'arg':
            return f'{c} | {tw}[{c}] | {ctx.builtin("int")} | {ctx.builtin("None")}'
        return f'{tw}[{c}]'
    if kind == 'LazyObjectProperty':
        if mode == 'arg':
            return '_Never_'
        return f'{ctx.support("TLazyObjectPtr")}[{_class_ref(ctx, t.cls)}]'
    if kind == 'SoftObjectProperty':
        if mode == 'arg':
            return '_Never_'
        return f'{ctx.support("TSoftObjectPtr")}[{_class_ref(ctx, t.cls)}]'
    if kind == 'SoftClassProperty':
        if mode == 'arg':
            return '_Never_'
        return f'{ctx.support("TSoftObjectPtr")}[{_uclass_ref(ctx)}]'
    if kind == 'FieldPathProperty':
        return '_Never_' if mode == 'arg' else '_FieldPathValue_'
    if kind == 'DelegateProperty':
        return '_Never_' if mode == 'arg' else '_DelegateValue_'
    if kind == 'MulticastInlineDelegateProperty':
        if mode == 'arg':
            return '_Never_'
        return f'{ctx.builtin("list")}[_DelegateBinding_]' if mode == 'out' else '_MulticastDelegateValue_'
    if kind == 'MulticastSparseDelegateProperty':
        return '_Never_' if mode == 'arg' else '_SparseDelegateValue_'
    if kind == 'StructProperty':
        if not t.struct or ctx.name(_struct_key(t.struct)) is None:
            return '_Never_' if mode == 'arg' else '_Any_'
        s = ctx.name(_struct_key(t.struct))
        if mode == 'get':
            return s
        if mode == 'out':
            v = ctx.name(_value_key(t.struct))
            return v if v is not None else s
        tup = _tuple_expr(t.struct, ctx, records_by_path or {})
        return f'{s} | {tup} | {ctx.builtin("dict")}[{ctx.builtin("str")}, _Any_]'
    if kind == 'ArrayProperty':
        if t.inner is None:
            return '_Any_'
        if mode == 'get':
            return f'{ctx.support("TArray")}[{_type_expr("get", t.inner, ctx, records_by_path)}]'
        if mode == 'out':
            return f'{ctx.builtin("list")}[{_type_expr("out", t.inner, ctx, records_by_path)}]'
        a = _type_expr('arg', t.inner, ctx, records_by_path)
        g = _type_expr('get', t.inner, ctx, records_by_path)
        return f'_Sequence_[{a}] | {ctx.support("TArray")}[{g}]'
    if kind == 'SetProperty':
        if t.element is None:
            return '_Any_'
        if mode == 'get':
            return f'{ctx.support("TSet")}[{_type_expr("get", t.element, ctx, records_by_path)}]'
        if mode == 'out':
            return f'{ctx.builtin("list")}[{_type_expr("out", t.element, ctx, records_by_path)}]'
        a = _type_expr('arg', t.element, ctx, records_by_path)
        g = _type_expr('get', t.element, ctx, records_by_path)
        return f'_Collection_[{a}] | {ctx.support("TSet")}[{g}]'
    if kind == 'MapProperty':
        if t.key is None or t.value is None:
            return '_Any_'
        if mode == 'get':
            return f'{ctx.support("TMap")}[{_type_expr("get", t.key, ctx, records_by_path)}, {_type_expr("get", t.value, ctx, records_by_path)}]'
        if mode == 'out':
            return f'{ctx.builtin("dict")}[{_type_expr("out", t.key, ctx, records_by_path)}, {_type_expr("out", t.value, ctx, records_by_path)}]'
        ka, va = _type_expr('arg', t.key, ctx, records_by_path), _type_expr('arg', t.value, ctx, records_by_path)
        kg, vg = _type_expr('get', t.key, ctx, records_by_path), _type_expr('get', t.value, ctx, records_by_path)
        return f'_Mapping_[{ka}, {va}] | {ctx.support("TMap")}[{kg}, {vg}]'
    return '_Any_'  # OptionalProperty, unknown


def _get_expr(p: PropertyRecord, ctx, records_by_path: dict) -> str:
    base = _type_expr('get', p.type, ctx, records_by_path)
    return f'{ctx.support("TFixedArray")}[{base}]' if p.array_dim > 1 else base


def _out_expr(p: PropertyRecord, ctx, records_by_path: dict) -> str:
    base = _type_expr('out', p.type, ctx, records_by_path)
    return f'{ctx.builtin("list")}[{base}]' if p.array_dim > 1 else base


def _arg_expr(p: PropertyRecord, ctx, records_by_path: dict, ref: bool = False) -> str:
    if p.array_dim > 1:
        elem = _type_expr('arg', p.type, ctx, records_by_path)
        if elem == '_Never_':
            return '_Never_'
        get_elem = _type_expr('get', p.type, ctx, records_by_path)
        return f'_Sequence_[{elem}] | {ctx.support("TFixedArray")}[{get_elem}]'
    if ref and p.type.kind == 'StructProperty' and p.type.struct and ctx.name(_struct_key(p.type.struct)) is not None:
        tup = _tuple_expr(p.type.struct, ctx, records_by_path)
        return f'{tup} | {ctx.builtin("dict")}[{ctx.builtin("str")}, _Any_]'
    return _type_expr('arg', p.type, ctx, records_by_path)


def _is_refused_arg(p: PropertyRecord, ctx, records_by_path: dict) -> bool:
    return _arg_expr(p, ctx, records_by_path) == '_Never_'


def _own_taken(rec, predefined_name: str | None) -> set[str]:
    """Names this record's OWN body binds (properties, functions including delegates, the predefined member)."""
    taken: set[str] = set()
    for p in rec.properties:
        taken.update(member_names(p.name))
    if isinstance(rec, ClassRecord):
        for f in rec.functions.values():
            taken.update(member_names(f.name))
    if predefined_name is not None:
        taken.add(predefined_name)
    return taken


