def write_stubs(source, out_dir) -> StubReport:
    """Write .pyi stubs of source's classes, structs and enums into out_dir."""
    t0 = time.perf_counter()
    out, _name = _check_out_dir(out_dir)
    records, source_text, skipped, predefined, close, (first_skip, last_skip) = _load_source(source)
    try:
        report = _write_stubs_impl(records, source_text, skipped, predefined, out)
    finally:
        close()
    seconds = time.perf_counter() - t0
    _log.info('wrote %d stub files (%d types) from %s to %s in %.1f s; removed %d stale files',
               report.files, report.types, report.source, report.out_dir, seconds, report.removed)
    if skipped > 0:
        _log.warning('%d type objects were not written (first: %s; last: %s)', skipped, first_skip, last_skip)
    return report


def _write_stubs_impl(records: list, source_text: str, skipped: int, predefined, out: str) -> StubReport:
    records_by_path = {r.path: r for r in records}
    packages = {r.package for r in records}
    root, node_of = _build_tree(packages)
    _assign_names(root)
    by_package, by_chain = _collect_modules(root, node_of)
    for r in records:
        by_package[r.package].types.append(r)
    names_of = {mod.modpath: _Names(mod.modpath, mod.folder) for mod in by_chain.values()}
    _assign_local_names(by_chain, names_of, records_by_path)
    written: dict[str, tuple] = {}
    for mod in by_chain.values():
        names = names_of[mod.modpath]
        for key in names.local:
            if not key.startswith('r:'):
                written[key] = mod.modpath
    for mod in by_chain.values():
        refs = _collect_module_refs(mod, records_by_path, predefined, written)
        _assign_imports(mod, names_of[mod.modpath], refs, written, by_chain, names_of)
    planned: dict[str, str] = {}
    modules: dict[str, str] = {}
    for pkg, mod in by_package.items():
        header = _header_line(pkg, source_text)
        text = _render_module(mod, header, written, names_of, by_chain, records_by_path, predefined)
        path = os.path.join(out, *mod.file.split('/'))
        planned[path] = text
        modules[pkg] = mod.file
    support_text = _support_header_line(source_text) + '\n' + _SUPPORT_MODULE_TEXT
    planned[os.path.join(out, '__init__.pyi')] = support_text
    files, removed = _write_module_files(out, planned)
    return StubReport(out, source_text, files, len(records), removed, skipped, modules)

