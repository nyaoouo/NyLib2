def _predefined_type_expr(path: str, ctx) -> str:
    if path == '/Script/Engine.Level':
        return f'{ctx.support("TArray")}[{_class_ref(ctx, "/Script/Engine.Actor")} | None]'
    return f'{ctx.support("TMap")}[{ctx.support("FName")}, _RawPointer_ | None]'


def _declared_predefined(rec, predefined) -> tuple[str, int, str] | None:
    """(name, value, label) of rec's predefined member, when it would be declared."""
    if predefined is None:
        return None
    hit = predefined(rec.path)
    if hit is None:
        return None
    key, value, label = hit
    name = key.rsplit('.', 1)[-1]
    if not isinstance(label, str) or not label.startswith(('auto:', 'profile:')) or value <= 0:
        return None
    own_names = set()
    for p in rec.properties:
        own_names.update(member_names(p.name))
    if name in own_names:
        return None
    return name, value, key


