def usable(n: str) -> bool:
    """A name a script can write as a source identifier."""
    if not isinstance(n, str):
        raise TypeError(f'n must be str, got {type(n).__name__}')
    return n.isidentifier() and not keyword.iskeyword(n) and unicodedata.normalize('NFKC', n) == n


def _path_str(value, name: str) -> str:
    try:
        s = os.fspath(value)
    except TypeError:
        raise TypeError(f'{name} must be str or os.PathLike, got {type(value).__name__}') from None
    if not isinstance(s, str):
        raise TypeError(f'{name} must be str or os.PathLike, got {type(value).__name__}')
    return s


def _is_link(path: str) -> bool:
    if os.path.islink(path):
        return True
    try:
        return bool(os.lstat(path).st_file_attributes & 0x400)  # FILE_ATTRIBUTE_REPARSE_POINT
    except (AttributeError, OSError):
        return False


def _spell(part: str) -> str:
    s = unicodedata.normalize('NFKC', part)
    s = ''.join(c if ('_' + c).isidentifier() else '_' for c in s)
    if s == '':
        return '_'
    if not s.isidentifier():
        s = '_' + s
    if keyword.iskeyword(s) or s.casefold() in _DEVICE_NAMES:
        s = s + '_'
    return s


# --------------------------------------------------------------------------- out_dir and source


def _check_out_dir(out_dir) -> tuple[str, str]:
    s = _path_str(out_dir, 'out_dir')
    if s == '':
        raise ValueError('out_dir must not be empty')
    out = os.path.abspath(s)
    name = os.path.basename(out)
    if not usable(name) or name in sys.stdlib_module_names or name == 'nylib':
        raise ValueError(f'the last part of out_dir must be a Python package name that hides no module, got {name!r}: '
                          f'scripts import the stubs from it, e.g. {name}.Script.Engine')
    if os.path.exists(out) and not os.path.isdir(out):
        raise NotADirectoryError(f'{out} exists and is not a folder')
    return out, name


def _snapshot_source_text(snap: Snapshot) -> str:
    if snap.path is not None:
        name = os.path.basename(os.path.normpath(snap.path))
    else:
        name = snap.stem
    return f'snapshot {name}' if name else '(in memory)'


def _records_of_snapshot(snap: Snapshot) -> list:
    return [r for r in snap.types() if isinstance(r, (ClassRecord, StructRecord, EnumRecord))]


def _predefined_snapshot(snap: Snapshot):
    sources = snap.offsets.get('sources')
    sources = sources if isinstance(sources, dict) else {}

    def get(path: str):
        key = _PREDEFINED_OFF_KEYS.get(path)
        if key is None:
            return None
        node = snap.offsets
        for part in key.split('.'):
            if not isinstance(node, dict) or part not in node:
                return None
            node = node[part]
        if not isinstance(node, str):
            return None
        try:
            value = unhex(node)
        except ValueError:
            return None
        return key, value, sources.get(key, '')
    return get


def _predefined_live(ctx):
    def get(path: str):
        key = _PREDEFINED_OFF_KEYS.get(path)
        if key is None:
            return None
        try:
            value = _off_value(ctx.e, key)
        except AttributeError:
            return None
        return key, value, ctx.e.provenance.get(key, '')
    return get


def _records_of_live(ctx) -> tuple[list, int, str | None, str | None]:
    """(records, skipped, first_skip_sample, last_skip_sample); samples are None while skipped is 0."""
    table = ctx.index.table()
    emitted, records, skipped = set(), [], 0
    first_skip: str | None = None
    last_skip: str | None = None

    def note(path, index, reason):
        nonlocal first_skip, last_skip
        sample = f'{path}: {reason}' if path is not None else f'object {index}: {reason}'
        if first_skip is None:
            first_skip = sample
        last_skip = sample
    try:
        for rec in table:
            if rec.flags & EObjectFlags.ClassDefaultObject:
                continue
            try:
                cls = table[rec.class_index].address if rec.class_index >= 0 else ctx.e.mem.ptr(rec.address + ctx.e.off.UObject.Class)
                cf = ctx.index.cast_flags(cls)
            except MemoryReadError:
                skipped += 1
                note(None, rec.index, 'class not readable')
                continue
            if cf & _CF.Class:
                want = 'class'
            elif cf & _CF.Function:
                continue
            elif cf & _CF.Struct:
                want = 'struct'
            elif cf & _CF.Enum:
                want = 'enum'
            else:
                continue
            try:
                path = table.path(rec.index)
            except ValueError:
                skipped += 1
                note(None, rec.index, 'path not readable')
                continue
            if path in emitted:
                skipped += 1
                note(path, rec.index, 'a second object of this path')
                continue
            if ctx.closed:
                raise SessionError('the session was closed during write_stubs')
            try:
                record = ctx.types.type(path, rec.address)
            except MemoryReadError:
                skipped += 1
                note(path, rec.index, 'type not readable')
                continue
            if record is None or record.kind != want:
                skipped += 1
                note(path, rec.index, f'not a{"n" if want == "enum" else ""} {want}')
                continue
            emitted.add(path)
            records.append(record)
        if ctx.closed:
            raise SessionError('the session was closed during write_stubs')
    except SessionError:
        raise
    except BaseException as exc:
        if ctx.closed:
            raise SessionError('the session was closed during write_stubs') from exc
        raise
    return records, skipped, first_skip, last_skip


def _load_source(source):
    """(records, source_text, skipped, predefined(path), close(), (first_skip, last_skip)) for a snapshot
    folder, Snapshot or Unreal session."""
    from .runtime.session import Unreal  # lazy: write_stubs never makes nylib.ue.stubs import pipeline
    if isinstance(source, Unreal):
        if source._ctx.closed:
            raise SessionError('the session is closed')
        if source.types == 'snapshot':
            return _load_source(source.snapshot)
        records, skipped, first_skip, last_skip = _records_of_live(source._ctx)
        text = f'live types of {source.exe} (pe {hexs(source.target.pe_timestamp)} / {hexs(source.target.size_of_image)})'
        return records, text, skipped, _predefined_live(source._ctx), (lambda: None), (first_skip, last_skip)
    if isinstance(source, Snapshot):
        records = _records_of_snapshot(source)
        text = _snapshot_source_text(source)
        return records, text, 0, _predefined_snapshot(source), (lambda: None), (None, None)
    if isinstance(source, (str, os.PathLike)) and not isinstance(source, bool):
        path = _path_str(source, 'source')
        snap = Snapshot.load(path)
        try:
            records = _records_of_snapshot(snap)
            text = _snapshot_source_text(snap)
            predefined = _predefined_snapshot(snap)
        except BaseException:
            snap.close()
            raise
        return records, text, 0, predefined, snap.close, (None, None)
    raise TypeError(f'source must be a snapshot folder, a Snapshot or an Unreal session, got {type(source).__name__}')


# --------------------------------------------------------------------------- layout


class _Node:
    __slots__ = ('children', 'is_package', 'spelled')

    def __init__(self):
        self.children: dict[str, '_Node'] = {}
        self.is_package = False
        self.spelled: str | None = None


def _package_parts(package: str) -> tuple[str, ...]:
    parts = tuple(p for p in package.split('/') if p)
    return parts or ('_',)


def _build_tree(packages) -> tuple[_Node, dict]:
    root = _Node()
    node_of = {}
    for pkg in packages:
        parts = _package_parts(pkg)
        node = root
        for part in parts:
            node = node.children.setdefault(part, _Node())
        node.is_package = True
        node_of[pkg] = node
    return root, node_of


def _assign_names(root: _Node) -> None:
    def walk(node: _Node, reserved: tuple[str, ...]):
        used = {r.casefold() for r in reserved}
        for part in sorted(node.children):
            child = node.children[part]
            base = _spell(part)
            name, n = base, 2
            while name.casefold() in used:
                name = f'{base}_{n}'
                n += 1
            child.spelled = name
            used.add(name.casefold())
        for child in node.children.values():
            walk(child, ('__init__',))
    walk(root, ('__init__', *SUPPORT_NAMES))


class _Module:
    __slots__ = ('file', 'folder', 'modpath', 'types')

    def __init__(self, file: str, folder: tuple[str, ...], modpath: tuple[str, ...]):
        self.file = file
        self.folder = folder
        self.modpath = modpath
        self.types: list = []


def _collect_modules(root: _Node, node_of: dict) -> tuple[dict, dict]:
    """(package -> _Module, path -> _Module) over every package node, by walking the spelled tree."""
    by_package: dict[str, _Module] = {}
    by_chain: dict[tuple[str, ...], _Module] = {}

    def walk(node: _Node, chain: tuple[str, ...]):
        for part, child in node.children.items():
            cchain = chain + (child.spelled,)
            if child.is_package:
                if child.children:
                    file = '/'.join(cchain) + '/__init__.pyi'
                    folder = cchain
                else:
                    file = '/'.join(cchain[:-1] + (cchain[-1] + '.pyi',)) if len(cchain) > 1 else cchain[-1] + '.pyi'
                    folder = cchain[:-1]
                by_chain[cchain] = _Module(file, folder, cchain)
            walk(child, cchain)
    walk(root, ())
    for pkg, node in node_of.items():
        chain = _chain_of(root, _package_parts(pkg))
        by_package[pkg] = by_chain[chain]
    return by_package, by_chain


def _chain_of(root: _Node, parts: tuple[str, ...]) -> tuple[str, ...]:
    node, chain = root, ()
    for part in parts:
        node = node.children[part]
        chain = chain + (node.spelled,)
    return chain


def _rel_import(f_folder: tuple[str, ...], t_modpath: tuple[str, ...]) -> str:
    k = 0
    while k < len(f_folder) and k < len(t_modpath) and f_folder[k] == t_modpath[k]:
        k += 1
    return '.' * (len(f_folder) - k + 1) + '.'.join(t_modpath[k:])


